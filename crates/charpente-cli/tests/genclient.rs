//! `charpente gen-client` / `charpente check-client`, driven as real
//! subprocesses against a real app crate (TS-codegen spec §4).
//!
//! The fixture app is `examples/invoicing` — a workspace member, so its
//! `cargo build` shares the warm target dir, and a rich contract (twelve
//! routes, one of them a stream, a dozen wire types, two branded ids) rather
//! than a synthetic one. It is used READ-ONLY: the plan's staleness step
//! ("append a field to a wire type") would mutate a checked-in example crate
//! from a test, which leaves the repo broken whenever the test panics between
//! the edit and the restore. Staleness is simulated by editing the GENERATED
//! file instead — `check-client` compares the committed bytes against freshly
//! generated ones, so the oracle under test is exercised identically.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

// Process spawning is edge tooling here, outside the deterministic core
// (DESIGN.md §1) — this test drives the built `charpente` binary as a real
// subprocess, exactly as a user would (the same shape as tests/describe.rs;
// integration tests are separate binaries, so the helper is per-file).
#[allow(clippy::disallowed_methods)]
fn charpente() -> Command {
    Command::new(env!("CARGO_BIN_EXE_charpente"))
}

fn invoicing_dir() -> String {
    format!("{}/../../examples/invoicing", env!("CARGO_MANIFEST_DIR"))
}

/// A real lib-only crate: `cargo build` there produces no executable at all,
/// so it is the launch-error case without a synthetic fixture (borrowed from
/// tests/describe.rs).
fn zero_bin_dir() -> String {
    format!("{}/../charpente-core", env!("CARGO_MANIFEST_DIR"))
}

/// One `--out` path per test, so tests that run in parallel cannot read each
/// other's file.
fn out_path(tag: &str) -> PathBuf {
    let mut p = std::env::temp_dir();
    p.push(format!("charpente-t10-{tag}-{}.ts", std::process::id()));
    p
}

// The generated file is what these tests are about — reading and writing it
// is edge tooling outside the deterministic core (DESIGN.md §1); nothing
// inside charpente-core touches the filesystem directly.
#[allow(clippy::disallowed_methods)]
fn read(p: &Path) -> String {
    std::fs::read_to_string(p).unwrap_or_else(|e| panic!("reading {}: {e}", p.display()))
}

#[allow(clippy::disallowed_methods)]
fn write(p: &Path, s: &str) {
    std::fs::write(p, s).unwrap_or_else(|e| panic!("writing {}: {e}", p.display()));
}

#[allow(clippy::disallowed_methods)]
fn remove(p: &Path) {
    let _ = std::fs::remove_file(p);
}

fn run(args: &[&str]) -> Output {
    charpente().args(args).output().unwrap()
}

fn run_ok(args: &[&str]) -> Output {
    let out = run(args);
    assert_eq!(
        out.status.code(),
        Some(0),
        "{args:?}\nstdout: {}\nstderr: {}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    out
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

/// The floor every generated-file assertion owes BEFORE comparing two
/// generated files to each other.
///
/// `assert_eq!(first, second)` is green when both are empty, and both sides
/// of every comparison in this file come from the same `emit_client` — so a
/// mutation inside the emitter moves both sides equally and the equality
/// holds. An assert cannot catch a mutation of the thing it is derived from.
///
/// Every anchor below is a LITERAL. None is produced by calling into
/// `charpente_tsgen` (this crate does not import it), and each is pinned
/// either to text the runtime declares verbatim or to something
/// `examples/invoicing` declares in Rust — `create_customer` and
/// `list_invoices` are two of its `#[route]` handlers, `CustomerView` is one
/// of its `#[derive(Wire)]` types, and `Customer` is one of its `#[table]`s,
/// reached here as an `Id<Customer>` route param. So the anchors do not move
/// when the emitter moves.
///
/// Mutations this reddens, named because a floor nobody can name a mutation
/// for is decorative: `emit_client` returning `String::new()` or any prefix
/// of the file; `emit_types` dropping the branded-id pass; `routes::
/// emit_methods` dropping non-stream routes, its `camel` case conversion, or
/// its `async ` keyword; `lib.rs` dropping `runtime::RUNTIME` or the `class
/// Api` line.
fn assert_floor(ts: &str, what: &str) {
    assert!(
        ts.len() > 4000,
        "{what}: a client for invoicing's twelve routes and dozen wire types cannot be \
         {} bytes — an empty or truncated file would satisfy every equality below",
        ts.len()
    );
    for needle in [
        "// GENERATED by `charpente gen-client`. Do not edit.",
        "export type Result<T, E> =",
        "export class CursorRefused extends Error {",
        "export class ApiBase {",
        "export class Api extends ApiBase {",
        r#"export type CustomerId = string & { readonly __table: "Customer" };"#,
        "export interface CustomerView {",
        "  async createCustomer(",
        "  async listInvoices(",
    ] {
        assert!(
            ts.contains(needle),
            "{what}: the generated client must contain {needle:?}\n--- file ---\n{ts}"
        );
    }
}

#[test]
fn gen_client_writes_a_client_for_the_app_at_dir() {
    let out = out_path("writes");
    remove(&out);
    let result = run_ok(&[
        "gen-client",
        "--dir",
        &invoicing_dir(),
        "--out",
        out.to_str().unwrap(),
    ]);
    assert_floor(&read(&out), "gen-client");
    assert!(
        stderr(&result).contains(out.to_str().unwrap()),
        "gen-client must say where it wrote: {}",
        stderr(&result)
    );
}

#[test]
fn gen_client_is_byte_identical_on_a_second_run() {
    let out = out_path("identical");
    let args = [
        "gen-client",
        "--dir",
        &invoicing_dir(),
        "--out",
        out.to_str().unwrap(),
    ];
    run_ok(&args);
    let first = read(&out);
    // The floor comes first: without it this test is green against an
    // `emit_client` that returns `String::new()`, since both runs would.
    assert_floor(&first, "first run");
    run_ok(&args);
    let second = read(&out);
    assert_eq!(
        first, second,
        "spec §4: generation must be byte-deterministic, across processes"
    );
}

#[test]
fn check_client_passes_on_a_fresh_file() {
    let out = out_path("fresh");
    let dir = invoicing_dir();
    let path = out.to_str().unwrap();
    run_ok(&["gen-client", "--dir", &dir, "--out", path]);
    // Same reason as above: `check-client` re-derives its comparison from the
    // same emitter `gen-client` used, so the comparison alone cannot see a
    // change common to both sides. The floor is what an emitter mutation
    // reddens.
    assert_floor(&read(&out), "the file check-client is about to accept");
    let result = run(&["check-client", "--dir", &dir, "--out", path]);
    assert_eq!(
        result.status.code(),
        Some(0),
        "a fresh client must exit 0\nstderr: {}",
        stderr(&result)
    );
}

#[test]
fn check_client_fails_on_a_stale_file_and_names_the_fix() {
    let out = out_path("stale");
    let dir = invoicing_dir();
    let path = out.to_str().unwrap();
    run_ok(&["gen-client", "--dir", &dir, "--out", path]);

    // Staleness, in the shape it reaches CI: the committed file no longer
    // matches what the app's contract generates. A renamed method is the
    // cheapest faithful stand-in for the Rust-side rename that causes it, and
    // unlike an appended line it lands the difference mid-file, which is the
    // branch `first_difference` exists for.
    let fresh = read(&out);
    write(
        &out,
        &fresh.replace("async createCustomer(", "async createBuyer("),
    );

    let result = run(&["check-client", "--dir", &dir, "--out", path]);
    assert_eq!(
        result.status.code(),
        Some(1),
        "a stale client must exit 1\nstderr: {}",
        stderr(&result)
    );
    let err = stderr(&result);
    // Hard rule 5: name the contract, the site, and the fix.
    assert!(err.contains("stale"), "name the contract violated: {err}");
    assert!(err.contains(path), "name the site: {err}");
    assert!(
        err.contains("charpente gen-client"),
        "the failure must name the fix (hard rule 5): {err}"
    );
    // And show WHAT drifted, without dumping the file into the log.
    assert!(
        err.contains("first difference at line"),
        "CI must see what drifted: {err}"
    );
    assert!(
        err.contains("createBuyer") && err.contains("createCustomer"),
        "both sides of the first difference must be shown: {err}"
    );
    assert!(
        err.len() < fresh.len(),
        "the diagnostic must not dump the whole generated file ({} bytes) into the log: \
         {} bytes",
        fresh.len(),
        err.len()
    );
}

#[test]
fn check_client_on_a_missing_file_exits_one_and_names_the_fix() {
    let out = out_path("missing");
    remove(&out);
    let result = run(&[
        "check-client",
        "--dir",
        &invoicing_dir(),
        "--out",
        out.to_str().unwrap(),
    ]);
    assert_eq!(
        result.status.code(),
        Some(1),
        "a missing client is a failure, not a usage error\nstderr: {}",
        stderr(&result)
    );
    let err = stderr(&result);
    assert!(err.contains(out.to_str().unwrap()), "name the site: {err}");
    assert!(
        err.contains("charpente gen-client"),
        "the failure must name the fix (hard rule 5): {err}"
    );
}

#[test]
fn an_unknown_flag_exits_two_and_names_the_valid_flags() {
    for verb in ["gen-client", "check-client"] {
        let result = run(&[verb, "--frobnicate", "x"]);
        assert_eq!(
            result.status.code(),
            Some(2),
            "a usage error is 2, not 1\nstderr: {}",
            stderr(&result)
        );
        let err = stderr(&result);
        assert!(err.contains("--frobnicate"), "{verb}: {err}");
        assert!(err.contains("--dir, --out"), "{verb}: {err}");
    }
}

#[test]
fn a_flag_with_no_value_exits_two() {
    let result = run(&["gen-client", "--out"]);
    assert_eq!(result.status.code(), Some(2), "stderr: {}", stderr(&result));
    assert!(
        stderr(&result).contains("--out requires a value"),
        "{}",
        stderr(&result)
    );
}

#[test]
fn an_app_crate_with_no_binary_exits_two_not_one() {
    // A launch error is 2 — never 1, which would tell CI the client is stale
    // when the truth is that nothing could be built to compare it against.
    let out = out_path("nobin");
    let result = run(&[
        "gen-client",
        "--dir",
        &zero_bin_dir(),
        "--out",
        out.to_str().unwrap(),
    ]);
    assert_eq!(
        result.status.code(),
        Some(2),
        "stdout: {}\nstderr: {}",
        String::from_utf8_lossy(&result.stdout),
        stderr(&result)
    );
    assert!(
        stderr(&result).contains("no binary target"),
        "{}",
        stderr(&result)
    );
}
