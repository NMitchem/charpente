//! The `emits(...)` drift oracle (TS-codegen spec §5), run against a REAL
//! app rather than a test-only one.
//!
//! `crates/charpente/tests/describe.rs` already carries this check over its
//! own in-file fixture; this one exists because the whole point of
//! `ts-fixture-app` is that a client is generated from it and compiled. A
//! declaration that drifted from the handler here would put a `FeedEvent`
//! union in front of `tsc` naming events the route never sends — and `tsc`
//! cannot tell, because both halves of that lie are generated from the same
//! declaration.

use charpente::http::App;
use charpente::wire::TypeSchema;
use charpente_sim::{FaultConfig, Sim};
use charpente_tsgen::emit_client;

fn fixture_app() -> App {
    let sim = Sim::with_faults(0x7357_0011, FaultConfig::none());
    ts_fixture_app::build_app(Box::new(sim.disk()), Box::new(sim.entropy()))
        .expect("the fixture app must build under FaultConfig::none()")
}

/// Order-sensitive, like the charpente-side oracle: declaration order is the
/// order the generated union's arms appear in, so `emits(B, A)` against
/// `of::<A>().and::<B>()` is a real mismatch.
///
/// The floor assertion is what keeps this from passing vacuously — an
/// undeclared stream route is SKIPPED (`emits(...)` is optional, and `[]`
/// means "not declared", not "declares nothing"), so without the floor an
/// app that declared none would sail through an empty loop.
#[test]
fn the_declared_emits_set_matches_the_handlers_subscription() {
    let mut app = fixture_app();
    let declared: Vec<(&'static str, Vec<&'static str>)> = app
        .describe()
        .routes
        .iter()
        .filter(|r| r.stream && !r.emits.is_empty())
        .map(|r| (r.name, r.emits.iter().map(|e| e.event).collect()))
        .collect();
    assert_eq!(
        declared.len(),
        1,
        "the floor: this fixture has exactly one stream route with a declared \
         emits(...) (`feed`; `raw_feed` declares none on purpose), so an empty \
         loop below would be a vacuous pass — got {declared:?}"
    );
    for (name, emits) in declared {
        let actual = app
            .subscription_event_names(name)
            .expect("a stream route must expose its subscription's event names");
        assert_eq!(
            emits, actual,
            "route `{name}` declares emits{emits:?} but its Subscription names {actual:?}"
        );
    }
}

/// A coverage floor for the revive walker's conditional-spread branch
/// (fix round 1 re-review, N1; this round's R1). `InvoiceView::credit_note_cents`
/// is currently the ONLY field in this fixture shaped `optional == true` AND
/// `Option(Int64)` — the one combination that makes the walker emit
/// `... in v ? {} : {...}` rather than an unconditional property. Every
/// other gate (including `ts-fixture/src/int64-null-safety.test.ts`'s own
/// assertion) stays green if that field is deleted: the assertion checks
/// that a key is ABSENT from the response, which is trivially true once the
/// key no longer exists in the type at all — a vacuous pass with nothing
/// left exercising the branch. This test pins the SHAPE, not the field's
/// name, so a rename does not trip it, but losing the combination anywhere
/// in the contract does.
#[test]
fn some_field_is_both_optional_and_an_option_of_int64() {
    let app = fixture_app();
    let contract = app.describe();
    let has_the_shape = contract.types.iter().any(|t| match &t.schema {
        TypeSchema::Struct { fields } => fields.iter().any(|f| {
            f.optional
                && matches!(
                    &f.schema,
                    TypeSchema::Option(inner) if matches!(**inner, TypeSchema::Int64 { .. })
                )
        }),
        _ => false,
    });
    assert!(
        has_the_shape,
        "no field anywhere in this contract is both `optional` and `Option<Int64>` \
         (the shape that makes the revive walker emit its conditional spread, \
         `... in v ? {{}} : {{...}}`) — if `InvoiceView::credit_note_cents` was deleted \
         or reshaped, restore a field with this combination; without one, that walker \
         branch is generated by nothing and executed by nothing"
    );
}

/// A coverage floor for the SSE dispatch map's key set (chunk B1c, A1;
/// the sibling of `some_field_is_both_optional_and_an_option_of_int64`
/// above, for the same reason).
///
/// The map's keys are the DECLARED event list, independent of which payloads
/// need reviving: a payload carrying no `Int64` gets a `null` walker, never
/// an absent entry, or the runtime's `has(name)` guard would refuse a frame
/// the route did declare. That rule is only EXERCISED while this fixture
/// declares both kinds — `InvoicePaid` carries an `Int64` (`amount_cents`),
/// `InvoiceVoided` carries none.
///
/// Give `InvoiceVoided` an `Int64` field, or drop it from `emits(...)`, and
/// every other gate stays green while
/// `ts-fixture/src/int64-sse.test.ts`'s "a declared event whose payload
/// carries no Int64 still dispatches" runs against a payload that now has
/// one: the `null` branch would be generated by nothing and executed by
/// nothing. The mirror case is just as quiet — remove the last `Int64` from
/// every declared payload and the SSE revive itself stops being reached.
///
/// It reads what the REAL emitter wrote for this app's contract rather than
/// re-deciding "does this payload carry an `Int64`" with a traversal of its
/// own, which could drift from the emitter's and call a floor covered when
/// it is not. The assertions are on the SHAPE of the emitted map, so a
/// renamed event or payload does not trip them.
#[test]
fn the_generated_dispatch_map_carries_both_a_walker_and_a_null_entry() {
    let app = fixture_app();
    let ts = emit_client(&app.describe());
    let at = ts
        .find("opts, new Map([")
        .expect("this fixture's declared stream route must emit a per-event dispatch map");
    let tail = &ts[at..];
    let map = &tail[..tail.find("]));").expect("the emitted map must close") + 4];
    assert!(
        map.contains("=> revive"),
        "no declared event payload in this contract carries an `Int64`, so the SSE revive \
         path is generated by nothing and executed by nothing — restore an `Int64` field on \
         a payload some route declares in `emits(...)`: {map}"
    );
    assert!(
        map.contains(", null]"),
        "every declared event payload in this contract carries an `Int64`, so the map's \
         `null` walker — A1's rule that a declared event with nothing to revive still gets \
         an ENTRY, not an absent one — is generated by nothing and executed by nothing; \
         restore a declared event whose payload has no `Int64`: {map}"
    );
}
